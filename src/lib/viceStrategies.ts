/** Look up a strategy by id */
export function getViceStrategy(id: string): ViceStrategy | undefined {
  return VICE_STRATEGIES.find(v => v.id === id);
}

/** Group strategies by category */
export function getVicesByCategory(): Record<string, ViceStrategy[]> {
  return VICE_STRATEGIES.reduce((acc, v) => {
    if (!acc[v.category]) acc[v.category] = [];
    acc[v.category].push(v);
    return acc;
  }, {} as Record<string, ViceStrategy[]>);
}
